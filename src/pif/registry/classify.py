"""Класс активов по названию фонда.

Категория в реестре ЦБ (рыночные финансовые инструменты, комбинированный и т. п.) для выбора
фонда почти бесполезна: 396 из 562 фондов попадают в одну группу. Поэтому рядом с ней считаем
свой класс активов. Это эвристика по названию, и на сайте она подписана как расчётная.
"""

from __future__ import annotations

import re

_RULES: tuple[tuple[str, str], ...] = (
    ("Драгоценные металлы", r"золот|драгоцен|серебр|платин|паллади|gold"),
    ("Денежный рынок", r"денежн\w* рын|ликвидност|сбережени|накопительн|ежедневн\w* процент|казначейск|ключев\w* ставк"),
    ("Облигации", r"облигац|бонд|bond|долгов|рантье|фиксированн\w* доход|ежемесячн\w* доход"),
    ("Акции", r"акци|индекс|компани\w* роста|голубые фишки|дивиденд|ipo|технолог|нефт|энерг|металлург|ресурс|потребительск"),
    ("Смешанные", r"сбалансир|смешанн|баланс|портфел|стратег|всепогод|вечный|цель 20"),
    ("Недвижимость", r"недвижим|рентн\w* доход|арендн"),
    ("Хедж-стратегии", r"хедж|hedge"),
)


def asset_class(name: str) -> str:
    lowered = name.lower().replace("ё", "е")
    quoted = re.findall(r"[«\"“]([^»\"”]+)[»\"”]", lowered)
    haystacks = [" ".join(quoted), lowered] if quoted else [lowered]
    for haystack in haystacks:
        for label, pattern in _RULES:
            if re.search(pattern, haystack):
                return label
    return "Прочие"
